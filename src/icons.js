const ATTRS = 'viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" '
  + 'stroke-linecap="round" stroke-linejoin="round"';

// Decorative by default: the words beside the icon carry the meaning, so
// screen readers skip it. With a label it stands for those words instead.
// An unknown name throws so a typo fails a test instead of rendering nothing.
export function icon(name, { label } = {}) {
  if (!Object.hasOwn(ICONS, name)) throw new Error(`unknown icon: ${name}`);
  const a11y = label === undefined
    ? 'aria-hidden="true" focusable="false"'
    : `role="img" aria-label="${escape(label)}" focusable="false"`;
  return raw(`<svg class="icon icon-${name}" ${ATTRS} ${a11y}>${ICONS[name]}</svg>`);
}

// An icon before its words, for an element with the with-icon class. The
// words get their own box so a long label wraps beside the icon, not under it.
export function iconText(name, text) {
  return html`${icon(name)}<span>${text}</span>`;
}

// Longer than this, a first word is likely a pasted link, which must stay
// free to wrap rather than run off a phone screen.
const KEEP_MAX = 24;

// An icon inside running text, for centred labels and sentences where the
// lines should flow under the icon. Chrome will break a line straight after
// an inline svg, even with a word joiner, so the icon shares a nowrap box
// with the first word.
export function iconInline(name, text) {
  const [, first, rest] = /^(\S*)([\s\S]*)$/.exec(String(text));
  if (Array.from(first).length > KEEP_MAX) return html`${icon(name)}${text}`;
  return html`<span class="nowrap">${icon(name)}${first}</span>${rest}`;
}
